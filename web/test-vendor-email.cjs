const fs=require('fs'),path=require('path'),assert=require('assert')
const ts=require(require.resolve('typescript',{paths:[process.env.EXB_CLIENT||process.cwd()]}))
const source=fs.readFileSync(path.join(__dirname,'src/runtime/vendor-email.ts'),'utf8')
const mod={exports:{}}
new Function('exports',ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText)(mod.exports)
const url=mod.exports.vendorEmailUrl('TEST A&B',123,'450 feet (custom)','vendor@example.test')
const parsed=new URL(url)
assert.equal(decodeURIComponent(parsed.pathname),'vendor@example.test')
assert.equal(parsed.searchParams.get('subject'),'Public notice mailing - TEST A&B')
assert(parsed.searchParams.get('body').includes('Cleaned mailing destinations: 123'))
assert(parsed.searchParams.get('body').includes('450 feet (custom)'))
assert(!parsed.searchParams.has('attachment'))
assert(mod.exports.vendorEmailUrl('TEST',1,'300 feet').startsWith('mailto:?'))
for(const address of ['x@y.test\r\nBcc:other@y.test','not-an-address','a@b.test?bcc=c@d.test'])assert.throws(()=>mod.exports.vendorEmailUrl('TEST',1,'300 feet',address))
